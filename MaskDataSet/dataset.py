# -*- coding: utf-8 -*-
"""
dataset.py
将 archive/ 中的 Pascal VOC (XML) 标注转换为 YOLO 格式，并合并进 train 文件夹，
同时重新生成 data.yaml，供 YOLOv8 训练使用。

类别映射（与现有 train 保持 2 类一致）：
    with_mask             -> 0 (mask)
    mask_weared_incorrect -> 0 (mask)   # 佩戴不规范，按要求归为 mask
    without_mask          -> 1 (no-mask)

运行：python dataset.py
"""

import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

# ============ 配置 ============
ROOT = Path(__file__).resolve().parent
ARCHIVE_DIR = ROOT / "archive"
ANN_DIR = ARCHIVE_DIR / "annotations"
IMG_DIR = ARCHIVE_DIR / "images"

TRAIN_IMG_DIR = ROOT / "train" / "images"
TRAIN_LBL_DIR = ROOT / "train" / "labels"

# 类别 -> id
CLASS_MAP = {
    "with_mask": 0,
    "mask_weared_incorrect": 0,   # 佩戴不规范 -> mask
    "without_mask": 1,
}
CLASS_NAMES = ["mask", "no-mask"]  # 索引即类别 id


def voc_to_yolo(xml_path: Path, out_label_path: Path) -> int:
    """把单个 XML 转成 YOLO txt。返回写出的有效框数量。"""
    try:
        tree = ET.parse(xml_path)
    except ET.ParseError as e:
        print(f"[WARN] 解析失败 {xml_path.name}: {e}")
        return 0

    root = tree.getroot()
    size = root.find("size")
    if size is None:
        print(f"[WARN] {xml_path.name} 缺少 <size>，跳过")
        return 0
    w = float(size.findtext("width", "0") or 0)
    h = float(size.findtext("height", "0") or 0)
    if w <= 0 or h <= 0:
        print(f"[WARN] {xml_path.name} 尺寸异常 w={w} h={h}，跳过")
        return 0

    lines = []
    for obj in root.findall("object"):
        name = obj.findtext("name")
        if name is None:
            continue
        if name not in CLASS_MAP:
            print(f"[WARN] {xml_path.name} 未知类别 '{name}'，跳过该框")
            continue
        cls_id = CLASS_MAP[name]
        bnd = obj.find("bndbox")
        if bnd is None:
            continue
        try:
            xmin = float(bnd.findtext("xmin"))
            ymin = float(bnd.findtext("ymin"))
            xmax = float(bnd.findtext("xmax"))
            ymax = float(bnd.findtext("ymax"))
        except TypeError:
            continue
        # 裁剪到图像范围
        xmin = max(0.0, min(xmin, w))
        xmax = max(0.0, min(xmax, w))
        ymin = max(0.0, min(ymin, h))
        ymax = max(0.0, min(ymax, h))
        if xmax <= xmin or ymax <= ymin:
            print(f"[WARN] {xml_path.name} 无效框 ({xmin},{ymin},{xmax},{ymax})，跳过")
            continue
        cx = (xmin + xmax) / 2.0 / w
        cy = (ymin + ymax) / 2.0 / h
        bw = (xmax - xmin) / w
        bh = (ymax - ymin) / h
        lines.append(f"{cls_id} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}")

    out_label_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_label_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
        if lines:
            f.write("\n")
    return len(lines)


def copy_image(src_img: Path, dst_img: Path) -> None:
    dst_img.parent.mkdir(parents=True, exist_ok=True)
    if not dst_img.exists():
        shutil.copy2(src_img, dst_img)


def clear_train_cache() -> None:
    """删除 train 的旧 YOLO 缓存，强制下次重建（避免新旧数据混用）。
    Roboflow 导出的缓存放在 split 根目录 (train/labels.cache)，而非 labels/ 内，
    所以两处都检查。"""
    candidates = []
    if TRAIN_LBL_DIR.exists():
        candidates += [TRAIN_LBL_DIR / n for n in ("labels.cache", "labels.cache.npy")]
    train_root = ROOT / "train"
    if train_root.exists():
        candidates += [train_root / n for n in ("labels.cache", "labels.cache.npy")]
    for p in candidates:
        if p.exists():
            try:
                p.unlink()
                print(f"[INFO] 删除旧缓存 {p}")
            except OSError as e:
                print(f"[WARN] 删除 {p} 失败: {e}")


def write_data_yaml() -> None:
    yaml_path = ROOT / "data.yaml"
    content = (
        "# YOLOv8 数据集配置 (auto-generated by dataset.py)\n"
        "# 类别: 0=mask, 1=no-mask\n"
        "# 路径相对于本 yaml 文件所在目录\n"
        f"train: train/images\n"
        f"val: valid/images\n"
        f"test: test/images\n\n"
        f"nc: {len(CLASS_NAMES)}\n"
        f"names: {CLASS_NAMES}\n"
    )
    yaml_path.write_text(content, encoding="utf-8")
    print(f"[INFO] 写出 {yaml_path}")


def main() -> None:
    assert ANN_DIR.exists(), f"标注目录不存在: {ANN_DIR}"
    assert IMG_DIR.exists(), f"图片目录不存在: {IMG_DIR}"
    TRAIN_IMG_DIR.mkdir(parents=True, exist_ok=True)
    TRAIN_LBL_DIR.mkdir(parents=True, exist_ok=True)

    xml_files = sorted(ANN_DIR.glob("*.xml"))
    print(f"[INFO] 共发现 {len(xml_files)} 个 XML 标注")

    n_ok = n_empty = n_skip = 0
    for xml in xml_files:
        stem = xml.stem
        img_src = IMG_DIR / f"{stem}.png"
        if not img_src.exists():
            print(f"[WARN] 找不到对应图片 {img_src.name}，跳过")
            n_skip += 1
            continue

        img_dst = TRAIN_IMG_DIR / img_src.name
        lbl_dst = TRAIN_LBL_DIR / f"{stem}.txt"

        n_box = voc_to_yolo(xml, lbl_dst)
        copy_image(img_src, img_dst)

        if n_box > 0:
            n_ok += 1
        else:
            # 无有效标注：保留空 txt 作为负样本
            if not lbl_dst.exists() or lbl_dst.stat().st_size == 0:
                lbl_dst.write_text("", encoding="utf-8")
            n_empty += 1

    print(f"[INFO] 转换完成: 有标注 {n_ok}，空标注 {n_empty}，跳过 {n_skip}")

    clear_train_cache()
    write_data_yaml()

    n_train_img = len(list(TRAIN_IMG_DIR.glob("*")))
    n_train_lbl = len(list(TRAIN_LBL_DIR.glob("*.txt")))
    print(f"[INFO] 合并后 train: images={n_train_img}, labels={n_train_lbl}")


if __name__ == "__main__":
    main()
